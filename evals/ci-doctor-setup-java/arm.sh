def copied(path):
    """`copied: no`, or `copied: yes (...)` when the adapter file is the kit's Java adapter, or more than half of its
    fixture files are there, the same, under the same name in the adapter's fixture dir"""
    # A known limit (the owner's call, #23): a text check, so a renamed copy (the stack's name and the fixtures' class
    # names changed) reads `copied: no`. The orchestrator reads the run's trace before it uses a generated adapter.
    try:
        kits = json.loads(read("kit-adapter.json"))
    except (OSError, ValueError):
        return "copied: not checked: harness: no kit-adapter.json in .git/ekit-eval/ (the scaffold's hashes)"
    why = [f"{path} is the kit's tests/fixtures/adapters/maven.toml"] \
        if digest(git("show", f"{ref}:{path}").stdout) == kits["adapter"] else []
    mine = path[:-len(".toml")] + ".r0/"
    ref_files, equal = sorted(kits["fixtures"]), 0
    for rel in ref_files:
        theirs = git("show", f"{ref}:{mine}{rel}")
        equal += theirs.returncode == 0 and digest(theirs.stdout) == kits["fixtures"][rel]
    if equal * 2 > len(ref_files):
        why.append(f"{equal} of {len(ref_files)} fixture files are maven.r0's")
    return f"copied: yes ({'; '.join(why)})" if why else "copied: no"


