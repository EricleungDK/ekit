def same(text):
    """text with comments (#, //, /* */) and whitespace dropped: a copy reads the same, whatever its comments"""
    return re.sub(r"\s+", "", re.sub(r"/\*[\s\S]*?\*/|//[^\n]*|#[^\n]*", "", text))


def digest(text):
    return hashlib.sha256(same(text).encode("utf-8")).hexdigest()


